-- ALTER_OFERTA_FILA_CAPTURA_LS_CLOB
-- Converte as 5 colunas de LISTA (LS_*) de VARCHAR2(600 CHAR) para CLOB, para
-- guardar os blobs de detalhes (tabelas key/value da Amazon etc.) SEM corte -- o
-- limite de 600 chars truncava listas longas e o de 4000 bytes do bind causava
-- ORA-01461 antes mesmo da SP (ver captureamazon-bug-ora01461-bind).
--
-- O Oracle 11g NAO permite ALTER ... MODIFY de VARCHAR2 para CLOB (ORA-22858);
-- por isso o padrao add-copy-drop-rename por coluna. Rodado com a fila quase
-- vazia (so o lote de teste tinha dados), entao a copia e barata.
--
-- DS_PRODUTO continua VARCHAR2, so ampliada de 350 para 600 CHAR (MODIFY direto,
-- pois ampliar VARCHAR2 e permitido).
--
-- Rodar no schema dono da tabela (BESAVE). Recompilar a SP _UPDATE depois.
-- =============================================================================

-- LS_CATEGORIA ---------------------------------------------------------------
ALTER TABLE OFERTA_FILA_CAPTURA ADD (LS_CATEGORIA_CLOB CLOB);
UPDATE OFERTA_FILA_CAPTURA SET LS_CATEGORIA_CLOB = LS_CATEGORIA;
ALTER TABLE OFERTA_FILA_CAPTURA DROP COLUMN LS_CATEGORIA;
ALTER TABLE OFERTA_FILA_CAPTURA RENAME COLUMN LS_CATEGORIA_CLOB TO LS_CATEGORIA;

-- LS_DETALHES_PRODUTO --------------------------------------------------------
ALTER TABLE OFERTA_FILA_CAPTURA ADD (LS_DETALHES_PRODUTO_CLOB CLOB);
UPDATE OFERTA_FILA_CAPTURA SET LS_DETALHES_PRODUTO_CLOB = LS_DETALHES_PRODUTO;
ALTER TABLE OFERTA_FILA_CAPTURA DROP COLUMN LS_DETALHES_PRODUTO;
ALTER TABLE OFERTA_FILA_CAPTURA RENAME COLUMN LS_DETALHES_PRODUTO_CLOB TO LS_DETALHES_PRODUTO;

-- LS_DETALHES_TECNICOS -------------------------------------------------------
ALTER TABLE OFERTA_FILA_CAPTURA ADD (LS_DETALHES_TECNICOS_CLOB CLOB);
UPDATE OFERTA_FILA_CAPTURA SET LS_DETALHES_TECNICOS_CLOB = LS_DETALHES_TECNICOS;
ALTER TABLE OFERTA_FILA_CAPTURA DROP COLUMN LS_DETALHES_TECNICOS;
ALTER TABLE OFERTA_FILA_CAPTURA RENAME COLUMN LS_DETALHES_TECNICOS_CLOB TO LS_DETALHES_TECNICOS;

-- LS_INFO_ADICIONAIS ---------------------------------------------------------
ALTER TABLE OFERTA_FILA_CAPTURA ADD (LS_INFO_ADICIONAIS_CLOB CLOB);
UPDATE OFERTA_FILA_CAPTURA SET LS_INFO_ADICIONAIS_CLOB = LS_INFO_ADICIONAIS;
ALTER TABLE OFERTA_FILA_CAPTURA DROP COLUMN LS_INFO_ADICIONAIS;
ALTER TABLE OFERTA_FILA_CAPTURA RENAME COLUMN LS_INFO_ADICIONAIS_CLOB TO LS_INFO_ADICIONAIS;

-- LS_COMPLEMENTO_PRODUTO -----------------------------------------------------
ALTER TABLE OFERTA_FILA_CAPTURA ADD (LS_COMPLEMENTO_PRODUTO_CLOB CLOB);
UPDATE OFERTA_FILA_CAPTURA SET LS_COMPLEMENTO_PRODUTO_CLOB = LS_COMPLEMENTO_PRODUTO;
ALTER TABLE OFERTA_FILA_CAPTURA DROP COLUMN LS_COMPLEMENTO_PRODUTO;
ALTER TABLE OFERTA_FILA_CAPTURA RENAME COLUMN LS_COMPLEMENTO_PRODUTO_CLOB TO LS_COMPLEMENTO_PRODUTO;

-- DS_PRODUTO: so amplia (VARCHAR2 350 -> 600 CHAR) -------------------------------
